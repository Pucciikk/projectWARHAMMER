def moving(m):
    # ---- шпиндель: патрон с тремя кулачками, заготовка ствола с нарезами
    s = m.bone("spindle", (0, AX_Y, AX_Z))
    s.lathe((-2.2, AX_Y, AX_Z), [(0.3, 0), (0.3, 0.2)], 14, "dark", "X")
    for k in range(3):
        a = k * 2 * math.pi / 3
        y, z = AX_Y + 0.17 * math.cos(a), AX_Z + 0.17 * math.sin(a)
        s.box((-2.0, y - 0.05, z - 0.05), (-1.86, y + 0.05, z + 0.05), "steel")
    s.lathe((-2.0, AX_Y, AX_Z), [(0.1, 0), (0.1, 4.0)], 10, "steel", "X")
    for k in range(4):                                          # нарезка: винтовые полосы проступают на заготовке
        a = k * math.pi / 2
        y, z = AX_Y + 0.102 * math.cos(a), AX_Z + 0.102 * math.sin(a)
        s.box((-1.8, y - 0.012, z - 0.012), (1.75, y + 0.012, z + 0.012), "rust")
    # ---- суппорт: каретка, резцедержатель, резец, маховичок
    c = m.bone("carriage", (-1.5, AX_Y, 1.1))
    c.box((-1.85, AX_Y - 0.52, 1.1), (-1.15, AX_Y + 0.52, 1.2), "dark", bevel=0.02)
    c.box((-1.7, AX_Y - 0.3, 1.2), (-1.3, AX_Y + 0.3, 1.3), "hull", bevel=0.015)
    c.box((-1.6, AX_Y - 0.56, 1.1), (-1.4, AX_Y - 0.5, 1.05), "brass")
    c.box((-1.6, AX_Y - 0.2, 1.3), (-1.4, AX_Y - 0.02, 1.36), "steel")
    c.wedge((-1.53, AX_Y - 0.1, 1.36), (-1.47, AX_Y + 0.06), (-1.51, AX_Y - 0.08, 1.42), (-1.49, AX_Y + 0.02), "dark")
    c.ring((-1.5, AX_Y - 0.62, 1.14), 0.07, 0.13, 0.03, 10, "red", "Y")
    c.lathe((-1.5, AX_Y - 0.5, 1.14), [(0.02, 0), (0.02, -0.12)], 4, "steel", "Y", base=False)
    c.lathe((-1.5, AX_Y - 0.02, 1.36), [(0.04, 0), (0.05, 0.03)], 5, "fire", base=False)   # раскалённая точка резания
    # ---- маховик с шестью спицами на шкиве передней бабки
    w = m.bone("flywheel", (-2.52, 0.68, 0.95))
    w.ring((-2.52, 0.68, 0.95), 0.3, 0.42, 0.14, 18, "hull")
    w.ring((-2.52, 0.68, 0.95), 0.38, 0.43, 0.04, 18, "brass")
    for k in range(5):
        a = k * 2 * math.pi / 5
        w.beam((-2.52, 0.68, 0.95), (-2.52, 0.68 + 0.34 * math.cos(a), 0.95 + 0.34 * math.sin(a)), 0.05, 0.05, "hull")
    # ---- капли масла
    for i in range(2):
        d = m.bone(f"oil_{i + 1}", (-0.4, AX_Y + 0.1, 2.02))
        d.lathe((-0.4, AX_Y + 0.1, 2.0), [(0, -0.04), (0.018, -0.015), (0.012, 0.02), (0, 0.04)], 5, "stain_gold", cap=False)


def pose(t):
    a = 2 * math.pi * t
    # суппорт едет ровно вперёд за 80 % цикла и быстро возвращается
    x = 3.1 * (t / 0.8) if t < 0.8 else 3.1 * (1 - (t - 0.8) / 0.2)
    p = {
        "spindle": {"rot": (360 * 4 * t, 0, 0)},
        "flywheel": {"rot": (360 * 4 * t, 0, 0)},
        "carriage": {"pos": (x, 0, 0)},
    }
    for i in range(2):
        u = (t * 3 + i * 0.5) % 1
        vis = 1 if u < 0.85 else 0
        p[f"oil_{i + 1}"] = {"pos": (0, 0, -0.62 * u * u), "scale": (vis, vis, vis)}
    return p


