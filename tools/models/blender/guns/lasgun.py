def moving(m):
    # ---- лазпакет: металлический короб с окном заряда
    x, y, z = MAG
    p = m.bone("mag", MAG)
    p.box((x - 0.05, y - 0.075, z - 0.14), (x + 0.05, y + 0.075, z), "steel", bevel=0.006)
    p.box((x - 0.052, y - 0.076, z - 0.13), (x + 0.052, y + 0.076, z - 0.118), "dark")
    p.box((x - 0.052, y - 0.076, z - 0.03), (x + 0.052, y + 0.076, z - 0.018), "dark")
    p.box((x - 0.0515, y - 0.03, z - 0.105), (x - 0.05, y + 0.03, z - 0.04), "stain_red")
    p.box((x + 0.05, y - 0.03, z - 0.105), (x + 0.0515, y + 0.03, z - 0.04), "stain_red")
    p.box((x - 0.03, y - 0.05, z - 0.15), (x + 0.03, y + 0.05, z - 0.14), "brass", bevel=0.002)
    # ---- рычаг зарядки на правой стороне
    lx, ly, lz = LEVER
    l = m.bone("lever", LEVER)
    l.box((lx - 0.016, ly - 0.01, lz - 0.01), (lx, ly + 0.012, lz + 0.01), "dark")
    l.box((lx - 0.024, ly - 0.015, lz - 0.015), (lx - 0.012, ly + 0.05, lz + 0.015), "brass", bevel=0.003)
    # ---- спусковой крючок
    tx, ty, tz = 0.0, 0.05, -0.078
    t = m.bone("trigger", (tx, ty, tz))
    t.beam((tx, ty, tz), (tx, ty + 0.018, tz - 0.05), 0.012, 0.012, "steel")
    # ---- руки и точки
    arm(m, "arm_r", GRIP)
    arm(m, "arm_l", FORE)
    locator(m, "muzzle", MUZZLE)


