    s.box((-0.0965, -0.07, 0.072), (-0.093, 0.05, 0.112), "gm_steel", bevel=0.001)
    for yy in (-0.05, -0.03, -0.01, 0.01, 0.03):
        s.box((-0.0972, yy - 0.003, 0.076), (-0.0962, yy + 0.003, 0.108), "gm_dark")
    # ---- спусковой крючок
    tx, ty, tz = 0.0, 0.098, -0.105
    t = m.bone("trigger", (tx, ty, tz))
    t.beam((tx, ty, tz), (tx, ty + 0.012, tz - 0.035), 0.014, 0.01, "gm_steel")
    t.beam((tx, ty + 0.012, tz - 0.035), (tx, ty + 0.032, tz - 0.06), 0.015, 0.01, "gm_steel")
    stock(m.bone("stock", (0, 0.282, 0)))
    arm(m, "arm_r", GRIP)
