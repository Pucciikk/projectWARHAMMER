def moving(m):
    x, y, z = MAG
    # ---- серповидный магазин: контур в плоскости YZ, толщина по X
    p = m.bone("mag", MAG)
    pts = []
    for i in range(9):
        k = i / 8
        pts.append((y - 0.085 - 0.05 * k * k, z - 0.31 * k))
    for i in range(9):
        k = 1 - i / 8
        pts.append((y + 0.085 - 0.07 * k * k, z - 0.31 * k))
    p.plate(pts, x - 0.05, x + 0.05, "hull")
    # рёбра и окошко счёта патронов
    for k in (0.2, 0.42, 0.64, 0.86):
        yy0, yy1 = y - 0.085 - 0.05 * k * k, y + 0.085 - 0.07 * k * k
        p.box((x - 0.052, yy0, z - 0.31 * k - 0.009), (x + 0.052, yy1, z - 0.31 * k + 0.009), "dark")
    p.box((x + 0.05, y - 0.03, z - 0.18), (x + 0.053, y + 0.012, z - 0.04), "brass")
    p.box((x - 0.053, y - 0.03, z - 0.18), (x - 0.05, y + 0.012, z - 0.04), "brass")
    # ---- рукоятка перезарядки
    bx, by, bz = BOLT
    h = m.bone("bolt", BOLT)
    h.box((bx - 0.02, by - 0.02, bz - 0.014), (bx, by + 0.02, bz + 0.014), "steel")
    h.lathe((bx, by, bz), [(0.018, 0), (0.024, 0.008), (0.024, 0.045), (0.016, 0.052)], 8, "brass", "X")
    # ---- затворная рама в окне: бегает при выстреле
    s = m.bone("slide", (-0.1, -0.01, 0.09))
    s.box((-0.103, -0.07, 0.074), (-0.098, 0.05, 0.106), "steel", bevel=0.002)
    # ---- спусковой крючок
    tx, ty, tz = 0.0, 0.1, -0.1
    t = m.bone("trigger", (tx, ty, tz))
    t.beam((tx, ty, tz), (tx, ty + 0.02, tz - 0.055), 0.014, 0.014, "steel")
    arm(m, "arm_r", GRIP)
    arm(m, "arm_l", FORE)
    locator(m, "muzzle", MUZZLE)
    locator(m, "eject", EJECT)


