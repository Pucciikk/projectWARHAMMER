def moving(m):
    x, y, z = MAG
    # ---- серповидный магазин: контур в плоскости YZ, толщина по X
    p = m.bone("mag", MAG)
    pts = []
    for i in range(9):
        k = i / 8
        pts.append((y - 0.085 - 0.05 * k * k, z - 0.33 * k))
    for i in range(9):
        k = 1 - i / 8
        pts.append((y + 0.085 - 0.07 * k * k, z - 0.33 * k))
    contour(p, pts, x - 0.048, x + 0.048, "gm_mid", bevel=0.005)
    # рёбра, поддон, смотровая щель с латунными донцами болтов
    for k in (0.3, 0.6, 0.86):
        y0, y1 = y - 0.085 - 0.05 * k * k, y + 0.085 - 0.07 * k * k
        p.box((x - 0.0495, y0 - 0.001, z - 0.33 * k - 0.007), (x + 0.0495, y1 + 0.001, z - 0.33 * k + 0.007), "gm_dark", bevel=0.001)
    y0, y1 = y - 0.135 - 0.002, y + 0.015 + 0.002
    p.box((x - 0.052, y0, z - 0.348), (x + 0.052, y1, z - 0.325), "gm_brass", bevel=0.004)
    for s in (-1, 1):
        side_box(p, s * 0.048, s, 0.0012, y - 0.028, y + 0.012, z - 0.27, z - 0.05, "gm_rubber")
        for i in range(6):
            zz = z - 0.07 - i * 0.034
            yy = y - 0.008 - 0.05 * ((-zz + z) / 0.33) ** 2
            p.lathe((s * 0.049, yy, zz), [(0.0135, 0), (0.0135, s * 0.0016), (0.009, s * 0.0028)], 10, "gm_brass", "X", base=False)
    # ---- рукоятка затвора
    bx, by, bz = BOLT
    h = m.bone("bolt", BOLT)
    h.box((bx - 0.016, by - 0.016, bz + 0.03), (bx + 0.002, by + 0.016, bz + 0.056), "gm_steel", bevel=0.002)
    h.lathe((bx, by, bz + 0.043), [(0.015, 0), (0.021, 0.006), (0.021, 0.04), (0.017, 0.046)], 12, "gm_brass", "X")
    for d in (0.016, 0.028):
        h.ring((bx + d, by, bz + 0.043), 0.019, 0.0225, 0.004, 12, "gm_dark", "X")
    # ---- затворная рама в окне: бегает при выстреле
