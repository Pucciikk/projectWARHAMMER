def moving(m):
    # ---- валки: зубья входят друг в друга, поэтому зазора нет; на осях — латунные шестерни
    for name, y, phase_roll, phase_gear, side in (("roll_front", -ROLL_Y, 0, 0, -1), ("roll_rear", ROLL_Y, 15, 11.25, 1)):
        r = m.bone(name, (0, y, ROLL_Z))
        c = (0, y, ROLL_Z)
        r.gear(c, 0.25, 0.40, 1.34, 12, "steel", "X", phase_roll, fill=0.42, flank=0.09)
        for x in (-0.6, -0.2, 0.2, 0.6):                         # бандажи делят валок на диски
            r.ring((x, y, ROLL_Z), 0.1, 0.28, 0.05, 24, "rust")
        r.lathe((-1.0, y, ROLL_Z), [(0.06, 0), (0.06, 2.1)], 10, "steel", "X")
        r.gear((GX, y, ROLL_Z), 0.285, 0.36, 0.1, 16, "brass", "X", phase_gear)
        r.lathe((GX - 0.05, y, ROLL_Z), [(0.1, 0), (0.08, -0.03), (0.05, -0.05)], 6, "dark", "X")
        for k in range(4):                                       # пустоты-окна в диске
            a = math.pi / 2 * k + math.pi / 4
            at = Vector((GX, y + 0.17 * math.cos(a), ROLL_Z + 0.17 * math.sin(a)))
            r.lathe(at + Vector((0.052, 0, 0)), [(0.05, 0), (0.05, -0.104)], 8, "dark", "X")

    # ---- вал, ведущая шестерня, маховик с шестью спицами и кривошипом
    fw = m.bone("flywheel", (0, -ROLL_Y, DRIVE_Z))
    c = Vector((0, -ROLL_Y, DRIVE_Z))
    fw.lathe((-1.0, -ROLL_Y, DRIVE_Z), [(0.05, 0), (0.05, 2.3)], 10, "steel", "X")
    fw.gear((GX, -ROLL_Y, DRIVE_Z), 0.285, 0.36, 0.1, 16, "brass", "X", 11.25)
    fw.lathe((GX - 0.05, -ROLL_Y, DRIVE_Z), [(0.1, 0), (0.08, -0.03), (0.05, -0.05)], 6, "dark", "X")
    fw.ring((FX, -ROLL_Y, DRIVE_Z), 0.47, 0.58, 0.14, 32, "hull")
    fw.ring((FX, -ROLL_Y, DRIVE_Z), 0.55, 0.59, 0.05, 32, "brass")
    fw.lathe((FX - 0.08, -ROLL_Y, DRIVE_Z), [(0.14, 0), (0.14, 0.16)], 12, "dark", "X")
    for k in range(6):
        a = 60 * k
        fw.box((FX - 0.03, -ROLL_Y - 0.035, DRIVE_Z + 0.1), (FX + 0.03, -ROLL_Y + 0.035, DRIVE_Z + 0.5), "hull",
               rot=("X", a), around=c + Vector((FX, 0, 0)))
    fw.lathe((FX + 0.08, -ROLL_Y + CRANK, DRIVE_Z), [(0.05, 0), (0.05, 0.1)], 10, "steel", "X")      # палец кривошипа
    fw.box((FX + 0.06, -ROLL_Y + 0.08, DRIVE_Z - 0.06), (FX + 0.09, -ROLL_Y + CRANK + 0.06, DRIVE_Z + 0.06), "dark", bevel=0.01)

    # ---- шатун: начало в пальце, балка вдоль +Y
    rod = m.bone("conrod", (RX, -ROLL_Y + CRANK, DRIVE_Z))
    y0 = -ROLL_Y + CRANK
    rod.ring((RX, y0, DRIVE_Z), 0.05, 0.09, 0.05, 12, "dark")
    rod.box((RX - 0.02, y0 + 0.07, DRIVE_Z - 0.035), (RX + 0.02, y0 + ROD - 0.05, DRIVE_Z + 0.035), "steel", bevel=0.006)
    rod.box((RX - 0.028, y0 + 0.4, DRIVE_Z - 0.05), (RX + 0.028, y0 + 0.47, DRIVE_Z + 0.05), "brass")
    rod.ring((RX, y0 + ROD, DRIVE_Z), 0.03, 0.065, 0.05, 12, "dark")

    # ---- ползун со штоком (на нулевом кадре стоит в крайней передней точке кривошипа)
    ch = m.bone("crosshead", (RX, y0 + ROD, DRIVE_Z))
    y1 = y0 + ROD
    ch.box((RX - 0.045, y1 - 0.09, DRIVE_Z - 0.078), (RX + 0.045, y1 + 0.09, DRIVE_Z + 0.078), "dark", bevel=0.012)
    ch.lathe((RX, y1 + 0.08, DRIVE_Z), [(0.03, 0), (0.03, 0.6)], 8, "steel", "Y")

    # ---- нижняя челюсть черепа и стрелка манометра
    j = m.bone("jaw", (0, -1.12, 0.8))
    j.blob([(-1.12, 0.26, 0.07, 0, 0.62), (-1.36, 0.25, 0.08, 0, 0.6), (-1.47, 0.16, 0.07, 0, 0.59)], 8, "bone")
