def smooth(x):
    return x * x * (3 - 2 * x)


def state(t):
    """Цикл печи: тележка едет к люку и обратно, заслонка поднимается, толкатель давит кокс, заслонка садится."""
    cart = -1.0 * smooth(min(1, t / 0.2)) if t < 0.3 else -1.0 * (1 - smooth(min(1, (t - 0.3) / 0.2)))
    door = 0.0
    if 0.5 <= t < 0.6:
        door = smooth((t - 0.5) / 0.1)
    elif 0.6 <= t < 0.88:
        door = 1.0
    elif 0.88 <= t < 0.98:
        door = 1 - smooth((t - 0.88) / 0.1)
    ram = 0.0
    if 0.6 <= t < 0.74:
        ram = smooth((t - 0.6) / 0.14)
    elif 0.74 <= t < 0.88:
        ram = 1 - smooth((t - 0.74) / 0.14)
    return cart, door * 0.92, ram * -0.2


def animate(objs, sc):
    frames = int(LOOP * 24)
    for f in range(frames + 1):
        cart, door, ram = state(f / frames)
        objs["cart"].location = (0, 1.0 + cart, 2.2)
        objs["door"].location = (0, -1.16, 0.9 + door)
        objs["ram"].location = (0, 1.46 + ram, 0.92)
        for n in ("cart", "door", "ram"):
            objs[n].keyframe_insert("location", frame=f + 1)
    sc.frame_set(1)


def tracks():
    steps = 48
    cart, door, ram, flame = {}, {}, {}, {}
    for i in range(steps + 1):
        t = i / steps
        c, d, r = state(t)
        key = f"{LOOP * t:.4f}"
        cart[key] = [0, 0, round(c * 16, 3)]
        door[key] = [0, round(d * 16, 3), 0]
        ram[key] = [0, 0, round(r * 16, 3)]
        flame[key] = [1, round(1 + 0.3 * math.sin(8 * math.pi * t) + 0.15 * math.sin(22 * math.pi * t), 3), 1]
    return {"cart": {"position": cart}, "door": {"position": door}, "ram": {"position": ram}, "stack_flame": {"scale": flame}}, LOOP


