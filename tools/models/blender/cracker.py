LOOP, STEPS = 2.0, 40
TX, TY = -0.25, 0.25               # ось колонны
STACK = (1.02, 1.02)               # факел


def frame(m):
    f = m.bone("frame")
    f.plinth(-1.48, -1.48, 1.48, 1.48)
    # ---- топка: кирпич и стальной пояс, спереди устье
    f.box((-1.15, -0.72, 0.3), (0.65, 1.22, 1.3), "brick", bevel=0.04)
    f.box((-1.18, -0.75, 0.42), (0.68, 1.25, 0.5), "dark")
    f.box((-1.18, -0.75, 1.22), (0.68, 1.25, 1.34), "dark", bevel=0.015)
    f.box((-0.72, -0.76, 0.54), (0.22, -0.71, 1.12), "dark")
    f.plate_xz([(-0.6, 0.6), (0.1, 0.6), (0.1, 0.92), (-0.08, 1.06), (-0.42, 1.06), (-0.6, 0.92)], -0.78, -0.75, "rust")
    f.plate_xz([(-0.52, 0.64), (0.02, 0.64), (0.02, 0.9), (-0.12, 1.0), (-0.38, 1.0), (-0.52, 0.9)], -0.8, -0.78, "fire")
    for x in (-0.46, -0.3, -0.14, 0.02):
        f.box((x - 0.018, -0.82, 0.6), (x + 0.018, -0.8, 1.02), "dark")
    # ---- колонна с катализатором
    f.lathe((TX, TY, 1.34), [(0.72, 0), (0.72, 0.1), (0.56, 0.16), (0.56, 2.72), (0.46, 2.98), (0.24, 3.12), (0.12, 3.18)], 16, "hull", base=False)
    for z in (1.86, 2.5, 3.14, 3.78):
        f.ring((TX, TY, z), 0.53, 0.62, 0.08, 16, "brass", "Z")
    for k in range(8):
        a = k * math.pi / 4
        f.bolt((TX + 0.6 * math.cos(a), TY + 0.6 * math.sin(a), 2.5), "Z", 0.026, 0.02, "steel")
    # люк-иллюминатор: виден раскалённый катализатор
    f.ring((TX, TY - 0.57, 2.82), 0.14, 0.23, 0.08, 12, "brass", "Y")
    f.lathe((TX, TY - 0.56, 2.82), [(0.14, 0), (0.14, -0.012)], 12, "fire", "Y", base=False)
    for s in (-1, 1):
        f.bolt((TX + s * 0.18, TY - 0.61, 2.82), "Y", 0.024, -0.018, "steel")
    f.skull(TX, TY - 0.5, 3.42, 0.34, augmetic=False)
    # площадка с лестницей вокруг колонны
    f.ring((TX, TY, 3.42), 0.57, 0.86, 0.04, 16, "dark", "Z")
    for k in range(8):
        a = k * math.pi / 4 + 0.3
        x, y = TX + 0.84 * math.cos(a), TY + 0.84 * math.sin(a)
        if y < TY - 0.3:
            continue
        f.lathe((x, y, 3.42), [(0.015, 0), (0.015, 0.34)], 4, "steel", base=False)
    f.ring((TX, TY, 3.75), 0.82, 0.86, 0.018, 16, "steel", "Z")
    f.ladder(TX - 0.62, TY + 0.78, 1.34, 3.42)
    # ---- теплообменник справа: горизонтальный бак
    f.lathe((1.03, -0.15, 1.68), [(0.18, -0.68), (0.32, -0.6), (0.32, 0.6), (0.18, 0.68)], 12, "steel", "Y")
    for y in (-0.5, 0.2):
        f.ring((1.03, y, 1.68), 0.3, 0.36, 0.06, 12, "dark", "Y")
    f.box((0.82, -0.62, 0.3), (1.24, -0.44, 1.42), "dark", bevel=0.01)
    f.box((0.82, 0.16, 0.3), (1.24, 0.34, 1.42), "dark", bevel=0.01)
    f.pipe([(1.03, -0.15, 2.0), (1.03, -0.15, 2.72), (0.65, 0.05, 2.98), (TX + 0.5, TY - 0.1, 3.0)], 0.07, 8, "rust")
    f.pipe([(0.67, -0.1, 1.68), (0.45, -0.1, 1.7)], 0.07, 8, "rust")
    # ---- холодильник: батарея трубок
    for i in range(5):
        y = -1.3 + i * 0.13
        f.lathe((1.15, y, 0.3), [(0.045, 0), (0.045, 1.05)], 6, "brass", base=False)
    f.box((0.8, -1.4, 1.3), (1.42, -0.72, 1.42), "dark", bevel=0.015)
    f.box((0.8, -1.4, 0.3), (1.42, -0.72, 0.44), "hull", bevel=0.015)
    f.pipe([(1.1, -1.05, 1.42), (1.1, -0.82, 1.5), (1.03, -0.62, 1.68)], 0.05, 6, "rust")
    # ---- факел
    x, y = STACK
    f.lathe((x, y, 0.3), [(0.17, 0), (0.17, 0.2), (0.1, 0.28), (0.1, 3.9), (0.15, 3.94), (0.15, 4.22)], 8, "rust", base=False)
    for z in (1.3, 2.3, 3.3):
        f.ring((x, y, z), 0.09, 0.13, 0.05, 8, "hazard", "Z")
    f.pipe([(TX + 0.15, TY + 0.1, 4.46), (0.45, 0.65, 4.42), (x, y, 3.9)], 0.05, 6, "rust")
    f.beam((x, y, 2.1), (0.42, 0.95, 1.3), 0.04, 0.04, "dark")
    # ---- подача насоса
    f.box((-1.42, -1.38, 0.3), (-0.7, -0.78, 1.0), "hull", bevel=0.03)
    f.box((-1.44, -1.2, 0.5), (-1.42, -0.9, 0.82), "screen")
    f.pipe([(-1.1, -0.78, 0.82), (-1.1, -0.6, 0.94), (-1.2, 0.0, 1.3), (TX - 0.5, TY, 1.5)], 0.06, 8, "rust")
    f.lathe((-1.06, -1.14, 1.0), [(0.05, 0), (0.05, 0.26)], 6, "steel", base=False)
    f.seal((0.6, -0.75, 1.0), "Y", -1)
    f.seal((TX + 0.4, TY - 0.45, 2.32), "Y", -1)


def moving(m):
    w = m.bone("pump_wheel", (-1.06, -1.14, 1.3))
    w.ring((-1.06, -1.14, 1.3), 0.17, 0.24, 0.05, 12, "brass", "Z")
    for k in range(4):
        a = k * math.pi / 2
        w.beam((-1.06, -1.14, 1.3), (-1.06 + 0.2 * math.cos(a), -1.14 + 0.2 * math.sin(a), 1.3), 0.035, 0.035, "steel")
    # ---- пламя топки: три языка
    for i, (x, h) in enumerate(((-0.42, 0.28), (-0.25, 0.36), (-0.08, 0.26))):
        fl = m.bone(f"flame_{i}", (x, -0.83, 0.62))
        fl.lathe((x, -0.83, 0.62), [(0.075, 0), (0.05, h * 0.5), (0, h)], 5, "fire", base=False)
    # ---- факел: живой огонь
    x, y = STACK
    s = m.bone("stack_flame", (x, y, 4.22))
    s.lathe((x, y, 4.22), [(0.13, 0), (0.19, 0.16), (0.1, 0.42), (0.03, 0.62), (0, 0.72)], 7, "fire", base=False)
    # ---- стрелка манометра на панели
    n = m.bone("needle", (-0.9, -0.79, 0.3))
    n.box((-0.905, -0.8, 0.3), (-0.895, -0.79, 0.42), "eye") if False else None
    n.box((TX - 0.004, TY - 0.62, 2.82), (TX + 0.11, TY - 0.615, 2.827), "eye")


def pose(t):
    a = 2 * math.pi * t
    p = {"pump_wheel": {"rot": (0, 0, 360 * 2 * t)}, "needle": {"rot": (0, 18 * math.sin(a * 3) + 8 * math.sin(a * 5), 0)}}
    for i in range(3):
        s = 0.85 + 0.25 * math.sin(a * (3 + i) + i * 2)
        p[f"flame_{i}"] = {"scale": (1, 1, s)}
    s = 1.0 + 0.16 * math.sin(a * 5) + 0.1 * math.sin(a * 9 + 1)
    p["stack_flame"] = {"scale": (1 + 0.08 * math.sin(a * 7), 1 + 0.08 * math.sin(a * 6), s)}
    return p


